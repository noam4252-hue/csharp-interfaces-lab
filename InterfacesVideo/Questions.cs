/*
משימה 1 — מימוש מחלקת Drone

Drone הוא כלי תחבורה המסוגל לעוף. כדי להפעיל אותו צריך להטעין אותו.

א. השלימו את כותרת המחלקה לפי כללי ההורשה ומימוש הממשקים:
