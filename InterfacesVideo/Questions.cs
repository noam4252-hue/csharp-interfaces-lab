ב. הוסיפו שתי תכונות מתאימות:
   - שם הדגם של הרחפן, מסוג string.
   - אחוז הסוללה, מסוג int. הניחו שערכו בין 0 ל-100.
   בחרו שמות מתאימים לתכונות והגדירו בנאי שמקבל את שני הערכים.
   אפשר להשתמש בייצוג התכונות שלמדתם בכיתה; אין צורך ב-protected.

ג. ממשו את Fly לפי החתימה של הממשק:
   - אם אחוז הסוללה נמוך מ-10, הדפיסו שהרחפן אינו יכול להמריא,
     בלי לשנות את אחוז הסוללה.
   - אחרת, הדפיסו הודעת טיסה הכוללת את שם הדגם,
     והפחיתו 10 מאחוז הסוללה.

ד. ממשו את Charge לפי החתימה של הממשק:
   הגדירו את אחוז הסוללה ל-100 והדפיסו הודעת טעינה הכוללת
   את שם הדגם ואחוז הסוללה לאחר הטעינה.

שמרו את החתימות הקיימות: הפעולות אינן מקבלות פרמטרים ואינן
מחזירות ערך. ההודעות ואחוז הסוללה מאפשרים לעקוב אחר הפעולות.
*/

using System;

public class Drone: Vehicle, IFlyable, IChargeable
{
    private string model;
    private int battery;
    public Drone(string model, int battery)
    {
        this.model = model;
        this.battery = battery;
    }
    public int Battery
    {
        get { return battery; }
        set { this.battery = value; }
    }
    public void Fly()
    {
        if (battery < 10)
            Console.WriteLine(model + " cannot take off - battery is " + battery + "%");
        else
        {
            Console.WriteLine(model + "is flying");
            battery -= 10;
        }
    }
    public void Charge()
    {
        battery = 100;
        Console.WriteLine(model + " charged - battery is " + battery + "%");
    }
    public string ChargingStatus()
    {
        if (battery < 10) return "Empty";
        if (battery < 30) return "Low";
        return "Ready";
    }
}

